export const searchText = value => String(value??'').normalize('NFKD').replace(/[\u0300-\u036f]/g,'').toLowerCase().replace(/['’‘]/g,'').replace(/[^a-z0-9]+/g,' ').trim();
const pieces = new Map(Object.entries(NAMED_PIECES).map(([name,id])=>[searchText(name),id]));
const known = id => typeof id==='string' && Object.hasOwn(SET_NAMES,id) ? id : '';
export function itemSet(item) {
 if(!item||!['Armor','Weapons'].includes(item.group)||[131,561].includes(item.templateIndex))return {setId:'',setName:''};
 const setId=known(item.sigil?.set);
 return {setId,setName:SET_NAMES[setId]||''};
}
export function listingSet(row) {
 const setId=known(row.setId)||(row.rarity==='aetheric'?pieces.get(searchText(row.name)):'')||'';
 return {setId,setName:SET_NAMES[setId]||''};
}

